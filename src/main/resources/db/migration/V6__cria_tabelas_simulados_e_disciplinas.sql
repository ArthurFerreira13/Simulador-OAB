CREATE TABLE simulado_sessao (
                                 id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 usuario_id              BIGINT NOT NULL REFERENCES usuarios(id),
                                 prova_id                INTEGER NOT NULL REFERENCES provas(id),
                                 status                  VARCHAR(20) NOT NULL CHECK (status IN ('EM_ANDAMENTO','ABANDONADO','CONCLUIDO')),
                                 tempo_limite_segundos   INTEGER NOT NULL,
                                 iniciado_em             TIMESTAMPTZ NOT NULL DEFAULT now(),
                                 finalizado_em           TIMESTAMPTZ
);

CREATE INDEX idx_simulado_sessao_usuario ON simulado_sessao (usuario_id);

CREATE UNIQUE INDEX uq_sessao_em_andamento ON simulado_sessao (usuario_id)
    WHERE status = 'EM_ANDAMENTO';

CREATE TABLE simulado_sessao_questao (
                                         id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         sessao_id           BIGINT NOT NULL REFERENCES simulado_sessao(id),
                                         questao_id          INTEGER NOT NULL REFERENCES questoes(id),
                                         ordem               INTEGER NOT NULL,
                                         marcada_revisao     BOOLEAN NOT NULL DEFAULT false,
                                         UNIQUE (sessao_id, questao_id)
);

CREATE TABLE resposta_simulado (
                                   id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   sessao_id           BIGINT NOT NULL REFERENCES simulado_sessao(id),
                                   questao_id          INTEGER NOT NULL REFERENCES questoes(id),
                                   alternativa_id      BIGINT REFERENCES alternativas(id),
                                   respondido_em       TIMESTAMPTZ NOT NULL DEFAULT now(),
                                   UNIQUE (sessao_id, questao_id)
);

CREATE TABLE resultado_simulado (
                                    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    sessao_id               BIGINT NOT NULL UNIQUE REFERENCES simulado_sessao(id),
                                    total_questoes          INTEGER NOT NULL,
                                    acertos                 INTEGER NOT NULL,
                                    erros                   INTEGER NOT NULL,
                                    brancos                 INTEGER NOT NULL,
                                    percentual_acerto       NUMERIC(5,2) NOT NULL,
                                    aprovado                BOOLEAN NOT NULL,
                                    tempo_gasto_segundos    INTEGER NOT NULL,
                                    calculado_em            TIMESTAMPTZ NOT NULL DEFAULT now()
);

