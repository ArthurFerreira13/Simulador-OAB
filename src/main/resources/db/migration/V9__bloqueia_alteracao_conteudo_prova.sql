-- V9__congela_conteudo_prova_com_bypass.sql
--
-- Bloqueia UPDATE e DELETE em provas/questoes/alternativas/disciplinas por padrão.
-- INSERT continua livre (ingestão de novas provas não é bloqueada).
--
-- Para autorizar uma correção pontual e controlada:
--     BEGIN;
--     SET LOCAL app.permitir_alteracao = 'true';
--     UPDATE questoes SET ...;
--     COMMIT;
--
-- Toda alteração (bloqueada ou autorizada via bypass) é registrada em
-- audit_alteracoes_conteudo. Tentativas bloqueadas NÃO geram linha de
-- auditoria, porque a exceção provoca rollback da transação inteira
-- (limitação inerente a triggers BEFORE em Postgres) — mas o próprio
-- erro lançado já serve como sinal imediato de tentativa indevida.
--
-- Tabelas congeladas: provas, questoes, alternativas, disciplinas.
-- NÃO congela: usuarios, administradores, simulado_*, resposta_simulado,
--              resultado_simulado, event_publication.

-- ---------------------------------------------------------------------------
-- 1. Tabela de auditoria
-- ---------------------------------------------------------------------------
CREATE TABLE audit_alteracoes_conteudo (
                                           id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                           tabela          TEXT NOT NULL,
                                           operacao        TEXT NOT NULL CHECK (operacao IN ('UPDATE','DELETE')),
                                           registro_id     TEXT,
                                           dados_antes     JSONB,
                                           dados_depois    JSONB,
                                           usuario_db      TEXT NOT NULL DEFAULT current_user,
                                           aplicacao       TEXT,
                                           executado_em    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_audit_conteudo_data   ON audit_alteracoes_conteudo (executado_em DESC);
CREATE INDEX idx_audit_conteudo_tabela ON audit_alteracoes_conteudo (tabela, executado_em DESC);
CREATE INDEX idx_audit_conteudo_reg_id ON audit_alteracoes_conteudo (tabela, registro_id);

-- ---------------------------------------------------------------------------
-- 2. Função híbrida: bloqueia por padrão, permite bypass explícito, audita
--    sempre que a operação é efetivamente executada (via bypass)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION congelar_com_bypass_auditado() RETURNS TRIGGER AS $$
DECLARE
v_bypass  TEXT;
    v_antes   JSONB;
    v_depois  JSONB;
    v_id      TEXT;
    v_app     TEXT;
BEGIN
    v_bypass := current_setting('app.permitir_alteracao', true);

    IF v_bypass IS DISTINCT FROM 'true' THEN
        RAISE EXCEPTION
            'Tabela % é imutável: % não é permitido sem SET LOCAL app.permitir_alteracao = ''true''',
            TG_TABLE_NAME, TG_OP;
END IF;

    -- Bypass ativo: registra auditoria e deixa a operação prosseguir
    v_app := current_setting('app.nome', true);

    IF TG_OP = 'DELETE' THEN
        v_antes  := to_jsonb(OLD);
        v_depois := NULL;
        v_id     := COALESCE(v_antes->>'id', '');
ELSE
        v_antes  := to_jsonb(OLD);
        v_depois := to_jsonb(NEW);
        v_id     := COALESCE(v_depois->>'id', '');
END IF;

INSERT INTO audit_alteracoes_conteudo
(tabela, operacao, registro_id, dados_antes, dados_depois, aplicacao)
VALUES
    (TG_TABLE_NAME, TG_OP, v_id, v_antes, v_depois, v_app);

RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

-- ---------------------------------------------------------------------------
-- 3. Triggers por tabela (BEFORE — decide se a operação acontece ou não)
-- ---------------------------------------------------------------------------
CREATE TRIGGER trg_congela_provas
    BEFORE UPDATE OR DELETE ON provas
    FOR EACH ROW EXECUTE FUNCTION congelar_com_bypass_auditado();

CREATE TRIGGER trg_congela_questoes
    BEFORE UPDATE OR DELETE ON questoes
    FOR EACH ROW EXECUTE FUNCTION congelar_com_bypass_auditado();

CREATE TRIGGER trg_congela_alternativas
    BEFORE UPDATE OR DELETE ON alternativas
    FOR EACH ROW EXECUTE FUNCTION congelar_com_bypass_auditado();

CREATE TRIGGER trg_congela_disciplinas
    BEFORE UPDATE OR DELETE ON disciplinas
    FOR EACH ROW EXECUTE FUNCTION congelar_com_bypass_auditado();