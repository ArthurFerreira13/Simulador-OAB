-- V12__cria_tabela_resposta_avulsa.sql
--
-- Resposta avulsa: cada par (usuario, questao) tem uma única linha.
-- Ausência de linha = não respondida OU questão anulada.
-- Última resposta prevalece (UNIQUE em usuario_id + questao_id).
--
-- Política LGPD: ON DELETE CASCADE — apagar o usuário apaga suas respostas.
--
-- Fonte de dados para:
--   - RF02.1 (filtro "já respondida / errada / não respondida")
--   - RF00.3 (métricas agregadas do dashboard)
--   - RF07.4 (elegibilidade de ranking)
--   - RF02.9 (EstatisticaQuestao, futura)
--
-- Não confundir com resposta_simulado (V6) — aquela é de sessão de simulado,
-- esta é de estudo avulso. Podem coexistir para a mesma questão/usuário.

CREATE TABLE resposta_avulsa (
                                 id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 usuario_id      BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
                                 questao_id      INTEGER NOT NULL REFERENCES questoes(id),
                                 alternativa_id  BIGINT NOT NULL REFERENCES alternativas(id),
                                 correta         BOOLEAN NOT NULL,
                                 respondido_em   TIMESTAMPTZ NOT NULL DEFAULT now(),
                                 CONSTRAINT uq_resposta_avulsa_usuario_questao UNIQUE (usuario_id, questao_id)
);

CREATE INDEX idx_resposta_avulsa_usuario
    ON resposta_avulsa (usuario_id, respondido_em DESC);

CREATE INDEX idx_resposta_avulsa_questao
    ON resposta_avulsa (questao_id);