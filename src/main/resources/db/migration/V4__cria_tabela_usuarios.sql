CREATE TABLE usuarios (
                          id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          email           VARCHAR(255) NOT NULL UNIQUE,
                          senha_hash      VARCHAR(255),
                          provedor_auth   VARCHAR(20) NOT NULL CHECK (provedor_auth IN ('LOCAL','GOOGLE','FACEBOOK','EMAIL_LINK')),
                          provedor_id     VARCHAR(255),
                          nome            VARCHAR(150) NOT NULL,
                          data_prova_alvo DATE,
                          criado_em       TIMESTAMPTZ NOT NULL DEFAULT now(),

                          CONSTRAINT chk_senha_obrigatoria_local
                              CHECK (provedor_auth <> 'LOCAL' OR senha_hash IS NOT NULL)
);

CREATE UNIQUE INDEX uq_usuarios_provedor ON usuarios (provedor_auth, provedor_id)
    WHERE provedor_id IS NOT NULL;